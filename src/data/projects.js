export const getProjectBySlug = (slug) => allProjects.find((project) => project.slug === slug) || null
export const getProjectType = (slug) => {
    if (professionalProjects.some((project) => project.slug === slug)) return 'professional'
    if (personalProjects.some((project) => project.slug === slug)) return 'personal'
    return null
}
